/**
 * Нормализация текста для сравнений.
 *
 * `toLocaleString('ru')` разделяет разряды **неразрывным** пробелом, а в
 * литерале теста стоит обычный. Сравнение молча не сходится, и выглядит
 * это как «строка не равна сама себе». Ловушка сработала трижды — поэтому
 * нормализация вынесена сюда, а не повторяется в каждом ожидании.
 *
 * Символы заданы escape-кодами: невидимый пробел в исходнике — та же
 * ловушка, только теперь в самом хелпере.
 */
const INVISIBLE_SPACES = /[\u00A0\u202F\u2009]/g;

export function plain(text: string): string {
  return text.replace(INVISIBLE_SPACES, ' ');
}
